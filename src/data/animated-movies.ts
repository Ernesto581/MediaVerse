function animatedMovie(
  id: string,
  title: string,
  folder: string,
  year?: number,
): MediaItem {
  const metadata = animatedMetadata[id]

  return {
    id,
    title,
    type: 'animated-movie',
    category: 'animated-movie',
    year,
    path: `${ROOT}//${folder}`,
    format: metadata.format,
    sizeBytes: metadata.sizeBytes,
    sizeFormatted: formatBytes(metadata.sizeBytes),
  }
}

